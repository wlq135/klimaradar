def german_intent_path(slug: str) -> str:
    return f"/{GERMAN_INTENT_COUNTRY.lower()}/{slug}"


def get_german_intent(slug: str) -> dict | None:
    """Return one formatted German high-intent page."""
    for page in GERMAN_INTENT_PAGES:
        if page["slug"] == slug.lower():
            return page | {
                "country": GERMAN_INTENT_COUNTRY,
                "html_lang": "de-DE",
                "path": german_intent_path(page["slug"]),
            }
    return None


def list_german_intents(exclude_slug: str | None = None) -> list[dict]:
    """Return compact metadata for internal links and the sitemap."""
    pages = []
    for page in GERMAN_INTENT_PAGES:
        if exclude_slug and page["slug"] == exclude_slug:
            continue
        pages.append(
            {
                "title": page["title"],
                "h1": page["h1"],
                "description": page["description"],
                "badge": page["badge"],
                "card_title": page["card_title"],
                "card_body": page["card_body"],
                "path": german_intent_path(page["slug"]),
            }
        )
    return pages


